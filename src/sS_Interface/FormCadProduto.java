    private void atualizarTabela() {

        DefaultTableModel dtm = (DefaultTableModel) tabelaSushi.getModel();
        dtm.setRowCount(0);

        for (Produto p : Produto.produto) {

            dtm.addRow(new Object[]{
                p.getCodProduto(),
                p.getTipo(),
                String.join(", ", p.getRecheio()),
                p.getPeixe(),
                p.getPrecoCusto(),
                p.getPrecoVenda(),
                p.getQuantDisponivel(),
                p.getQuantVendas()
            });
        }
    }

    private void jButtonCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCadastrarActionPerformed
        // TODO add your handling code here:
        jButtonVoltar.setEnabled(true);
        if (verificacaoFormCompleto()) {
            //------------------------------------------------------------------------------------------------
            int cod = Produto.gerarCod();
            double preco = Double.parseDouble(jTxtPreco.getText());
            int quantidade = Integer.parseInt(jTxtQuantidade.getText());
            String tipo = jComboBTipo.getSelectedItem().toString();
            String peixe = jComboBPeixe.getSelectedItem().toString();

            // Reinicia o array
            ArrayList<String> recheios = new ArrayList<>();
            double valorAcrescimoTotal = 0;

            // Verifica as caixas
            if (jCheckBCebolinha.isSelected()) {
                recheios.add("Cebolinha");
            }
            if (jCheckBCreamCheese.isSelected()) {
                recheios.add("Cream Cheese");
            }
            if (jCheckBGergelim.isSelected()) {
                recheios.add("Gergelim");
            }
            if (jCheckBPepino.isSelected()) {
                recheios.add("Pepino");
            }

            // Se não selecionou nenhum
            if (recheios.isEmpty()) {
                recheios.add("Sem recheio");
            }

            // Para cada recheio escolhido, custa R$5
            valorAcrescimoTotal = recheios.size() * 5;

            // Transforma a lista em string pronta pra tabela
            String listaRecheios = String.join(", ", recheios);

            //Cria um objeto tipo Conta com as informações!
            Produto produto = new Produto();
            produto.cadastrar(cod, tipo, acrescimo, peixe, preco, quantidade, 0);
            Produto.produto.add(produto);

            //Inicia a tabela
            DefaultTableModel dtm = (DefaultTableModel) tabelaSushi.getModel();

            //Cria linha na tabela
            //Cria a linha da tabela com os seguintes
            modeloSushi.addRow(new Object[]{cod, peixe, tipo, listaRecheios, quantidade, preco});
            // Tabela antes ---> dtm.addRow(new Object[]{cod, peixe, tipo, listaRecheios, quantidade, preco + valorAcrescimoTotal});
            double precoFinal = preco + valorAcrescimoTotal;
            produto.setPrecoVenda(precoFinal);
            jButtonAlterar.setEnabled(true);
            desabilitarEdicao();
            JOptionPane.showMessageDialog(rootPane, "Conta cadastrada com sucesso!");
            desabilitarBotoes();
            jButtonAlterar.setEnabled(true);
            jButtonLimpar.setEnabled(true);

        } else if (!verificacaoFormCompleto()) {
            JOptionPane.showMessageDialog(rootPane, "Preencha todas as informações para continuar!");
            habilitarEdicao();
            jButtonAlterar.setEnabled(false);
        }


    }//GEN-LAST:event_jButtonCadastrarActionPerformed

    private void jButtonAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAlterarActionPerformed
        // TODO add your handling code here:
        habilitarEdicao();

        int l = tabelaSushi.getSelectedRow();
        if (l == -1) {
            JOptionPane.showMessageDialog(rootPane, "Selecione um item para alterar!");
            return;
        }

        // Lê os valores editados (string dos campos), não sei se tem necessidade mas...
        String peixe = jComboBPeixe.getSelectedItem().toString();
        String tipo = jComboBTipo.getSelectedItem().toString();
        String qtdStr = jTxtQuantidade.getText().trim();
        String precoStr = jTxtPreco.getText().trim();

        // valida campos numéricos
        int qtd;
        double preco;
        // valida quantidade (somente números inteiros)
        if (!qtdStr.matches("\\d+")) {
            JOptionPane.showMessageDialog(rootPane, "Quantidade inválida. Informe um número inteiro.");
            return;
        }
        qtd = Integer.parseInt(qtdStr);

        // valida preço (somente números decimais com ponto OU inteiro)
        if (!precoStr.matches("\\d+(\\.\\d+)?")) {
            JOptionPane.showMessageDialog(rootPane, "Preço inválido. Use ponto como separador decimal.");
            return;
        }
        preco = Double.parseDouble(precoStr);

        // Monta lista de recheios
        ArrayList<String> lista = new ArrayList<>();
        if (jCheckBCebolinha.isSelected()) {
            lista.add("Cebolinha");
        }
        if (jCheckBCreamCheese.isSelected()) {
            lista.add("Cream Cheese");
        }
        if (jCheckBGergelim.isSelected()) {
            lista.add("Gergelim");
        }
        if (jCheckBPepino.isSelected()) {
            lista.add("Pepino");
        }
        if (lista.isEmpty()) {
            lista.add("Sem recheio");
        }
        String recheios = String.join(", ", lista);

        // Atualiza tabela com os TIPOS corretos (Integer e Double)
        modeloSushi.setValueAt(peixe, l, 1);
        modeloSushi.setValueAt(tipo, l, 2);
        modeloSushi.setValueAt(recheios, l, 3);
        modeloSushi.setValueAt(Integer.valueOf(qtd), l, 4);    // Integer
        modeloSushi.setValueAt(Double.valueOf(preco), l, 5);   // Double

        JOptionPane.showMessageDialog(rootPane, "Alterado com sucesso!");


    }//GEN-LAST:event_jButtonAlterarActionPerformed

