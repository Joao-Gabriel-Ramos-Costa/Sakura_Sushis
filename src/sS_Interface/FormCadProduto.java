    private void configurarSelecaoTabela() {
        jButtonVoltar.setEnabled(true);
        tabelaSushi.getSelectionModel().addListSelectionListener((e) -> {

            if (tabelaSushi.getSelectedRow() == -1) {
                return;
            }

            int l = tabelaSushi.getSelectedRow();

            // Preencher campos automaticamente:
            jComboBPeixe.setSelectedItem(modeloSushi.getValueAt(l, 1).toString());
            jComboBTipo.setSelectedItem(modeloSushi.getValueAt(l, 2).toString());
            jTxtQuantidade.setText(modeloSushi.getValueAt(l, 4).toString());
            jTxtPreco.setText(modeloSushi.getValueAt(l, 5).toString());

            // Recheios
            String recheios = modeloSushi.getValueAt(l, 3).toString();

            jCheckBCebolinha.setSelected(recheios.contains("Cebolinha"));
            jCheckBCreamCheese.setSelected(recheios.contains("Cream Cheese"));
            jCheckBGergelim.setSelected(recheios.contains("Gergelim"));
            jCheckBPepino.setSelected(recheios.contains("Pepino"));

            habilitarEdicao();
            jButtonAlterar.setEnabled(true);
        });
    }

    public boolean verificacaoFormCompleto() {
        boolean formularioCompleto = false;
        if (jTxtPreco.getText() != "" && jTxtQuantidade.getText() != "" && jComboBPeixe.getSelectedIndex() != 0 && jComboBTipo.getSelectedIndex() != 0) {
            formularioCompleto = true;
        }
        return formularioCompleto;
    }

